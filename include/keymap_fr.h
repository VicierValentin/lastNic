/**
 * keymap_fr.h — ASCII to USB HID keyboard report mapping for French AZERTY
 *
 * Use with lastnic -l fr when the target PC has a French AZERTY layout set.
 *
 * The BBB always sends positional HID keycodes (physical key positions).
 * This table maps each ASCII character to the physical key (+ modifier) that
 * produces it when the host interprets reports with the fr AZERTY layout.
 *
 * Key differences from US QWERTY:
 *   - a/z, q/w swapped at OS level  →  different HID positions
 *   - m is at the `;` position (HID 0x33)
 *   - digits 0-9 require Shift (unshifted number row = &é"'(-è_çà)
 *   - most symbols in different positions, many via AltGr (Right Alt, 0x40)
 *
 * AltGr combinations (Right Alt = modifier 0x40):
 *   ~  AltGr+2   #  AltGr+3   {  AltGr+4   [  AltGr+5
 *   |  AltGr+6   `  AltGr+7   \  AltGr+8   ^  AltGr+9
 *   @  AltGr+0   ]  AltGr+)   }  AltGr+=
 *
 * Based on the standard Linux XKB fr(azerty) symbol table.
 */

